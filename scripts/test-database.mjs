  await query(`update public.subjects set project_status='active' where id=$1`,[projectId]);
  assert.equal((await query(`select project_status from public.subjects where id=$1`,[projectId]))[0].project_status,'active');
  await query(`insert into public.topics(id,user_id,subject_id,title,mode,priority,due_on) values($1,$2,null,'جهز العرض','work','high',$3)`,[workTopic,A,today]);
  await query(`select public.set_work_state($1,'blocked','بانتظار الملف')`,[workTopic]);
  assert.equal((await query(`select work_state from public.topics where id=$1`,[workTopic]))[0].work_state,'blocked');
