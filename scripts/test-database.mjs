  assert.equal((await query(`select count(*)::integer as n from public.topics where id=$1`,[workTopic]))[0].n,0,'private work task must be hidden');
  await expectReject(()=>query(`select public.set_work_state($1,'done','')`,[workTopic]),'other user cannot complete a work task');
