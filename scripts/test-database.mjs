  const skippedSession='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaa07';
  await query(`select public.start_focus($1,$2,'focus',60,$3)`,[workTopic,plannedWork,skippedSession]);
  await admin();
